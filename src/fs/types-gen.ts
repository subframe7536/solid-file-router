import { relative } from 'node:path'

import { normalizePath } from './router'
import type { ModuleRef, RouteManifestEntry, RouteTreeEntry } from './types'

const HEADER = `// Generated by solid-file-router. Do not edit.
// Regenerated whenever a route file is added, changed or removed.`

const REF_TYPES = `  /** A code-split ref: the delivery adapter emits it as a dynamic import. */
  export interface FileRouteLazyRef<M = Record<string, unknown>> {
    src: string;
    import(): Promise<M>;
  }

  /** An eager ref: its picked exports are imported statically. */
  export interface FileRouteEagerRef<M = Record<string, unknown>> {
    /** The source module path — present when the convention emitted the ref lazy and \`codeSplitting: false\` delivered it eagerly. */
    src?: string;
    require(): M;
  }

  /** A flat entry of the route manifest. */
  export interface FileRouteEntry {
    path: string;
    page?: boolean;
    /** The page component is a server function; its \`$component\` is delivered eagerly. */
    server?: boolean;
    $component?: FileRouteLazyRef<any> | FileRouteEagerRef<any>;
    $$route?: FileRouteEagerRef<any>;
    [key: string]: unknown;
  }

  /** An entry of the nested \`pageRoutes\` view. */
  export interface FileRouteTreeEntry extends FileRouteEntry {
    id: string;
    children?: readonly FileRouteTreeEntry[];
  }`

const TYPED_MODULE = /\.([mc]?[jt]sx?)$/

function refType(ref: ModuleRef, kind: 'eager' | 'lazy', from: string): string {
  const name = kind === 'eager' ? 'FileRouteEagerRef' : 'FileRouteLazyRef'
  if (!TYPED_MODULE.test(ref.src)) {
    return name
  }
  const picks = ref.pick.filter((pick) => pick !== '$css').map((pick) => JSON.stringify(pick))
  if (!picks.length) {
    return name
  }
  let specifier = normalizePath(relative(from, ref.src)).replace(TYPED_MODULE, '')
  if (!specifier.startsWith('.')) {
    specifier = `./${specifier}`
  }
  const moduleType = `typeof import(${JSON.stringify(specifier)})`
  return `${name}<Pick<${moduleType}, Extract<${picks.join(' | ')}, keyof ${moduleType}>>>`
}

const isLazyRefKey = (key: string): boolean => key.startsWith('$') && !key.startsWith('$$')
const isEagerRefKey = (key: string): boolean => key.startsWith('$$')

function entryType(
  entry: RouteManifestEntry | RouteTreeEntry,
  indent: string,
  nested: boolean,
  from: string,
  codeSplitting: boolean,
): string {
  const inner = `${indent}  `
  const fields = [`path: ${JSON.stringify(entry.path)}`]
  if (nested && 'id' in entry) {
    fields.push(`id: ${JSON.stringify(entry.id)}`)
  }
  fields.push(`page: ${entry.page ? 'true' : 'false'}`)
  if (entry.server) {
    fields.push('server: true')
  }

  const refKeys = Object.keys(entry).filter(
    (key) => key.startsWith('$') && entry[key] !== undefined,
  )
  for (const key of refKeys) {
    const ref = entry[key] as ModuleRef
    const kind = isEagerRefKey(key) || !codeSplitting || ref.eager ? 'eager' : 'lazy'
    fields.push(`${key}: ${refType(ref, kind, from)}`)
  }

  if (!refKeys.some(isLazyRefKey)) {
    fields.push('$component?: undefined')
  }
  if (!refKeys.some(isEagerRefKey)) {
    fields.push('$$route?: undefined')
  }

  if (nested) {
    const children = (entry as RouteTreeEntry).children
    fields.push(
      children?.length
        ? `children: ${tupleType(children, inner, true, from, codeSplitting)}`
        : 'children?: undefined',
    )
  }
  return `{\n${fields.map((field) => `${inner}${field};`).join('\n')}\n${indent}}`
}

function tupleType(
  entries: readonly (RouteManifestEntry | RouteTreeEntry)[],
  indent: string,
  nested: boolean,
  from: string,
  codeSplitting: boolean,
): string {
  if (!entries.length) {
    return 'readonly []'
  }
  const inner = `${indent}  `
  const members = entries
    .map((entry) => `${inner}${entryType(entry, inner, nested, from, codeSplitting)}`)
    .join(',\n')
  return `readonly [\n${members}\n${indent}]`
}

export function serializeTypes(
  moduleId: string,
  routes: readonly RouteManifestEntry[],
  pageRoutes: readonly RouteTreeEntry[],
  from: string,
  codeSplitting = true,
): string {
  return `${HEADER}

declare module ${JSON.stringify(moduleId)} {
${REF_TYPES}

  /** The flat route manifest, in scan order. */
  const routes: ${tupleType(routes, '  ', false, from, codeSplitting)};
  export default routes;

  /** The page entries, nested by path with grouping segments stripped. */
  export const pageRoutes: ${tupleType(pageRoutes, '  ', true, from, codeSplitting)};
}
`
}
